import { katax } from 'katax-service-manager';
import type { ISqlDatabase } from 'katax-service-manager';
import type { PoolClient } from 'pg';

/**
 * Data access for the 'main' PostgreSQL connection.
 *
 * - `db()` narrows `katax.db('main')` (publicly typed as the broader
 *   IDatabaseService) to ISqlDatabase once, so no repository casts.
 * - `SqlExecutor` is what every repository function receives as its last
 *   parameter (`executor: SqlExecutor = db()`): the pool by default, or the
 *   transaction client when a controller/service runs several repository
 *   calls inside one `withTransaction`.
 */
export interface SqlExecutor {
  query<T = unknown>(sql: string, params?: unknown[]): Promise<T>;
}

export function db(): ISqlDatabase {
  return katax.db('main') as unknown as ISqlDatabase;
}

/** Kept for code generated by katax-cli <= 1.7.1, which types the callback as `Tx`. */
export type Tx = SqlExecutor;

/**
 * Runs `fn` inside one transaction on a dedicated pooled client: COMMIT on
 * success, ROLLBACK + rethrow on error, always release.
 *
 * Never send BEGIN/COMMIT through `db().query()`: each pool query may use a
 * different connection, so the statements would not share a transaction.
 */
export async function withTransaction<T>(fn: (tx: SqlExecutor) => Promise<T>): Promise<T> {
  const client = (await db().getClient()) as PoolClient;
  const tx: SqlExecutor = {
    query: async <R>(sql: string, params?: unknown[]) => (await client.query(sql, params)).rows as R
  };
  try {
    await client.query('BEGIN');
    const result = await fn(tx);
    await client.query('COMMIT');
    return result;
  } catch (error) {
    await client.query('ROLLBACK').catch(() => undefined);
    throw error;
  } finally {
    client.release();
  }
}

/**
 * Serialises a "check, then write" for one key inside the current
 * transaction (quota, max active sessions, max N per user). The lock is
 * released automatically at COMMIT/ROLLBACK.
 *
 *   await withTransaction(async (tx) => {
 *     await lockKey(tx, `sessions:${userId}`);
 *     ...count, revoke the oldest, insert...
 *   });
 */
export async function lockKey(tx: SqlExecutor, key: string): Promise<void> {
  await tx.query('SELECT pg_advisory_xact_lock(hashtext($1))', [key]);
}
